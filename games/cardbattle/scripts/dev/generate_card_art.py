def path(d, fill, stroke="#101b2a", width=2.2, extra=""):
    return f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{width}" stroke-linejoin="round" stroke-linecap="round" {extra}/>'


def circle(x, y, r, fill, stroke="none", width=1, extra=""):
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{width}" {extra}/>'


def lines(d, stroke, width=1.2, extra=""):
    return path(d, "none", stroke, width, extra)


def jewel(x, y, size, color):
    return (path(f"M{x} {y-size}l{size*.7} {size} {-size*.7} {size} {-size*.7} {-size}Z", color, GOLD, .8)
            + lines(f"M{x} {y-size}v{size*2}m{-size*.7} {-size}h{size*1.4}", "#fff9dc", .7))


def star(x, y, size, color):
    return path(f"M{x} {y-size}l{size*.25} {size*.75} {size*.75} {size*.25} {-size*.75} {size*.25} {-size*.25} {size*.75} {-size*.25} {-size*.75} {-size*.75} {-size*.25} {size*.75} {-size*.25}Z", color, "none")


def stars(width, height, count, seed):
    rng = random.Random(seed)
    return "".join(circle(round(rng.uniform(10, width-10), 2), round(rng.uniform(10, height-10), 2),
                          rng.choice([.5, .8, 1.1, 1.5]), rng.choice([GOLD, ICE, "#e6e5ed"]),
                          extra=f'opacity="{rng.uniform(.16, .6):.2f}"') for _ in range(count))


