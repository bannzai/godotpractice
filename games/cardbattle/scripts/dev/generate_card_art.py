def portrait_background(index):
    color = GOLD if index < 12 else ICE
    result = '<rect width="320" height="240" fill="url(#back)"/>'
    result += circle(162, 102, 134, "url(#aura)")
    for radius in (74, 88, 91, 111):
        result += circle(162, 111, radius, "none", color, .7, 'opacity=".18"')
    for angle in range(0, 360, 15):
        a = math.radians(angle + index * 7)
        x, y = 162 + math.sin(a) * 91, 111 + math.cos(a) * 91
        xx, yy = 162 + math.sin(a) * 97, 111 + math.cos(a) * 97
        result += lines(f"M{x:.1f} {y:.1f}L{xx:.1f} {yy:.1f}", color, .8, 'opacity=".4"')
    result += stars(320, 220, 39, 190 + index)
    result += path("M0 221Q61 191 113 214T218 215T320 203V240H0Z", "#08151f", "none")
    return result


