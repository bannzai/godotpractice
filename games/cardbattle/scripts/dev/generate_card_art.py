def character_parts(index, drawing):
    # 元の描画要素を分割し、部位の形状を別定義に重複させずに保持する。
    head_elements, accent_elements = [
        (range(6, 9), range(9, 13)),
        (range(5, 9), range(11, 15)),
        (range(3, 9), [0, 11]),
        (range(6, 10), range(0, 3)),
        (range(7, 12), range(13, 17)),
        (range(3, 12), [0]),
        (range(4, 7), [9, 10]),
        (range(4, 8), range(9, 13)),
        (range(5, 10), range(0, 3)),
        ([9, 10], [7, 8]),
        (range(5, 9), range(0, 3)),
        (range(19, 25), range(26, 32)),
        (range(4, 8), range(9, 14)),
        (range(4, 8), range(10, 15)),
        (range(3, 8), range(8, 11)),
        (range(6, 10), range(0, 3)),
        ([5, 6, 7, 8, 15, 16], range(10, 13)),
        (range(5, 14), range(0, 3)),
        (range(6, 11), [4, 5]),
        (range(5, 9), range(10, 13)),
        (range(5, 9), range(0, 3)),
        (range(5, 8), [8, 9]),
        (range(5, 9), range(0, 3)),
        (range(6, 10), range(11, 18)),
    ][index]
    layers = {"body": [], "head": [], "accent": []}
    for element_index, element in enumerate(ET.fromstring(f"<g>{drawing}</g>")):
        layer = "head" if element_index in head_elements else "accent" if element_index in accent_elements else "body"
        layers[layer].append(ET.tostring(element, encoding="unicode"))
    layers["head"].append(face_detail(index))
    for name, elements in layers.items():
        if not elements:
            raise ValueError(f"m{index:02d} の {name} が空です")
        write_svg(f"characters/m{index:02d}/{name}.svg", 320, 240, defs(index < 12) + "".join(elements))
    write_svg(f"characters/m{index:02d}/background.svg", 320, 240, defs(index < 12) + portrait_background(index))


def write_svg(name, width, height, body):
    destination = ART / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    content = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
               f'viewBox="0 0 {width} {height}">\n{body}\n</svg>\n')
    ET.fromstring(content)
